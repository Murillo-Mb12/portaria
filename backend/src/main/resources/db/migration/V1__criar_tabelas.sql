-- =====================================================
-- V1: criação das tabelas (executado uma única vez pelo Flyway)
-- Compatível com PostgreSQL e com o H2 (perfil h2).
-- =====================================================

CREATE TABLE tbl_funcionario (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR(100) NOT NULL,
    usuario VARCHAR(50)  NOT NULL UNIQUE,
    senha   VARCHAR(100) NOT NULL,                -- hash BCrypt
    perfil  VARCHAR(20)  NOT NULL
            CHECK (perfil IN ('ADMINISTRADOR', 'PORTEIRO'))
);

CREATE TABLE tbl_morador (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(100) NOT NULL,
    unidade  VARCHAR(50)  NOT NULL,
    telefone VARCHAR(20)  NOT NULL
);

-- Visitante = parente, cuidador ou amigo de um ou mais moradores
CREATE TABLE tbl_visitante (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(100) NOT NULL,
    documento VARCHAR(20)  NOT NULL UNIQUE,
    telefone  VARCHAR(20)  NOT NULL,
    vinculo   VARCHAR(20)  NOT NULL
              CHECK (vinculo IN ('FAMILIAR', 'CUIDADOR', 'AMIGO'))
);

-- Quais moradores cada visitante pode visitar (N:N)
CREATE TABLE tbl_visitante_morador (
    visitante_id BIGINT NOT NULL REFERENCES tbl_visitante (id),
    morador_id   BIGINT NOT NULL REFERENCES tbl_morador (id),
    PRIMARY KEY (visitante_id, morador_id)
);

CREATE TABLE tbl_veiculo (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa       VARCHAR(7)   NOT NULL UNIQUE,
    marca       VARCHAR(40)  NOT NULL,
    modelo      VARCHAR(40)  NOT NULL,
    cor         VARCHAR(30)  NOT NULL,
    tipo        VARCHAR(20)  NOT NULL
                CHECK (tipo IN ('VISITANTE', 'INSTITUICAO', 'OUTRO')),
    responsavel VARCHAR(100)          -- usado quando o veículo não é de visitante
);

-- Pessoas que podem usar o veículo (ex.: membros da mesma família) (N:N)
CREATE TABLE tbl_veiculo_visitante (
    veiculo_id   BIGINT NOT NULL REFERENCES tbl_veiculo (id),
    visitante_id BIGINT NOT NULL REFERENCES tbl_visitante (id),
    PRIMARY KEY (veiculo_id, visitante_id)
);

CREATE TABLE tbl_acesso (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo         VARCHAR(20)  NOT NULL CHECK (tipo IN ('PESSOA', 'VEICULO')),
    objetivo     VARCHAR(20)  NOT NULL CHECK (objetivo IN ('VISITA', 'DOACAO', 'OUTROS')),
    visitante_id BIGINT REFERENCES tbl_visitante (id),   -- visitante ou condutor
    morador_id   BIGINT REFERENCES tbl_morador (id),     -- morador visitado
    veiculo_id   BIGINT REFERENCES tbl_veiculo (id),
    nome         VARCHAR(100),                            -- pessoa sem cadastro (doação / outros)
    documento    VARCHAR(20),
    finalidade   VARCHAR(20)
                 CHECK (finalidade IN ('BAZAR', 'IGREJA', 'REUNIAO', 'IMPRENSA', 'OUTRO')),
    descricao    VARCHAR(255),                            -- itens doados ou observação
    entrada      TIMESTAMP    NOT NULL,
    saida        TIMESTAMP,
    CONSTRAINT ck_acesso_veiculo  CHECK ((tipo = 'VEICULO') = (veiculo_id IS NOT NULL)),
    CONSTRAINT ck_acesso_visita   CHECK (objetivo <> 'VISITA' OR (visitante_id IS NOT NULL AND morador_id IS NOT NULL)),
    CONSTRAINT ck_acesso_pessoa   CHECK (tipo <> 'PESSOA' OR objetivo = 'VISITA' OR nome IS NOT NULL),
    CONSTRAINT ck_acesso_outros   CHECK (objetivo <> 'OUTROS' OR finalidade IS NOT NULL),
    CONSTRAINT ck_acesso_periodo  CHECK (saida IS NULL OR saida >= entrada)
);

-- Consultas por período (RF10 / RF11) e lista de presentes
CREATE INDEX idx_acesso_entrada ON tbl_acesso (entrada);
CREATE INDEX idx_acesso_saida   ON tbl_acesso (saida);
